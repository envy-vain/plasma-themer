"""Launch the QML overlay picker and apply whatever it selects.

Everything expensive is baked here once and cached, so the QML side only draws plain images:
  card    rounded-corner PNG at card size (no runtime mask effect)
  blur    tiny pre-blurred JPEG for the backdrop (no runtime blur shader)
That keeps the picker smooth on weak GPUs and lets it run on Qt's software renderer.
"""
from __future__ import annotations

import fcntl
import json
import os
import subprocess
import threading
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from .core import CACHE, REPO, list_themes, lite, load_theme, qml_runtime, screen_wallpaper, state_get, state_set

ART = CACHE / "picker"
CARD_W, CARD_H, RADIUS = 460, 300, 20
VERSION = "v2"  # bump to invalidate baked art


def _paths(src: Path) -> tuple[Path, Path]:
    d = ART / src.parent.parent.name
    return d / f"{src.stem}-card-{VERSION}.png", d / f"{src.stem}-blur-{VERSION}.jpg"


def _fresh(out: Path, src: Path) -> bool:
    return out.exists() and out.stat().st_mtime >= src.stat().st_mtime


def bake(src: Path) -> tuple[str, str]:
    card, blur = _paths(src)
    if _fresh(card, src) and _fresh(blur, src):
        return str(card), str(blur)
    from PIL import Image, ImageDraw, ImageFilter

    from .core import _cover
    card.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(screen_wallpaper(src)) as im:
        c = _cover(im, CARD_W * 2, CARD_H * 2)  # 2x then downsample: smooth anti-aliased corners
        mask = Image.new("L", c.size, 0)
        ImageDraw.Draw(mask).rounded_rectangle((0, 0, *c.size), RADIUS * 2, fill=255)
        c.putalpha(mask)
        c.resize((CARD_W, CARD_H), Image.LANCZOS).save(card, optimize=True)
        b = _cover(im, 320, 180).filter(ImageFilter.GaussianBlur(9))
        b.point(lambda v: int(v * 0.75)).save(blur, quality=85)
    return str(card), str(blur)


def warm(workers: int | None = None) -> int:
    """Bake every wallpaper (themer setup). Parallel across cores; cached after the first run."""
    todo = [b for s in list_themes() for b in load_theme(s).backgrounds
            if not all(_fresh(p, b) for p in _paths(b))]
    if todo:
        with ProcessPoolExecutor(max_workers=workers or max(1, (os.cpu_count() or 2) - 1)) as ex:
            list(ex.map(bake, todo))
    return len(todo)


def build_data() -> dict:
    themes, missing = [], []
    for slug in list_themes():
        t = load_theme(slug)
        bgs = t.backgrounds
        saved = state_get(f"bg/{slug}")
        names = [b.name for b in bgs]
        sel = names.index(saved) if saved in names else 0
        wps = []
        for i, b in enumerate(bgs):
            card, blur = _paths(b)
            if i == sel:
                card, blur = map(Path, bake(b))  # the visible one must exist now
            elif not (_fresh(card, b) and _fresh(blur, b)):
                missing.append(b)
            wps.append({"file": b.name, "card": str(card), "blur": str(blur)})
        themes.append({
            "slug": slug,
            "name": t.name,
            "colors": {k: v for k, v in t.colors.items() if isinstance(v, str) and v.startswith("#")},
            "wallpapers": wps,
            "bg": sel,
        })
    if missing:  # finish the rest in the background while the picker is already up
        threading.Thread(target=lambda: [bake(b) for b in missing], daemon=True).start()
    return {"current": state_get("current", ""), "themes": themes, "lite": lite()}


DATA = CACHE / "picker.json"
LAUNCHER = CACHE / "pick.sh"


def write_data() -> Path:
    """Prepare the picker's data ahead of time (after every switch), so the hotkey never waits for Python."""
    CACHE.mkdir(parents=True, exist_ok=True)
    tmp = DATA.with_suffix(".tmp")
    tmp.write_text(json.dumps(build_data()))
    tmp.replace(DATA)
    return DATA


def write_launcher(themer_bin: str) -> Path | None:
    """Hotkey fast path: a tiny sh script that execs the QML runtime directly on the prepared data, and only
    calls back into Python (`themer pick-apply`) once something was chosen. Saves ~250 ms per open."""
    qml = qml_runtime()
    if not qml:
        return None
    soft = "" if any(Path("/dev/dri").glob("renderD*")) else "export QT_QUICK_BACKEND=software\n"
    LAUNCHER.parent.mkdir(parents=True, exist_ok=True)
    LAUNCHER.write_text(f"""#!/bin/sh
# generated by `themer setup` — opens the theme picker without starting Python first
data="{DATA}"
[ -s "$data" ] || exec "{themer_bin}" pick
# resident picker running? just ask it to show (instant)
pid=$(cat "{CACHE / 'resident.pid'}" 2>/dev/null)
if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then
  touch "{TRIGGER}/show.$$" && exit 0
fi
exec 9>"{CACHE / 'picker.lock'}"
flock -n 9 || exit 0  # already open
export QML_XHR_ALLOW_FILE_READ=1 QT_QUICK_CONTROLS_STYLE=Basic QT_FORCE_STDERR_LOGGING=1
{soft}"{qml}" "{REPO / 'picker/Picker.qml'}" -- "$data" 2>&1 >/dev/null | {{
  while IFS= read -r line; do
    case $line in
      *APPLY:*) sel=${{line#*APPLY:}}; "{themer_bin}" pick-apply "${{sel%%:*}}" "${{sel#*:}}" & ;;
    esac
  done
  wait  # the apply runs while the picker plays its closing animation
}}
""")
    LAUNCHER.chmod(0o755)
    return LAUNCHER


TRIGGER = CACHE / "trigger"
RESIDENT = CACHE / "pick-resident.sh"
SERVICE = Path.home() / ".config/systemd/user/plasma-themer-picker.service"


def write_resident(themer_bin: str) -> Path | None:
    """Background picker: loaded once, hidden, shown by the hotkey (~instant). ~50 MB private RAM."""
    qml = qml_runtime()
    if not qml:
        return None
    soft = "" if any(Path("/dev/dri").glob("renderD*")) else "export QT_QUICK_BACKEND=software\n"
    RESIDENT.write_text(f"""#!/bin/sh
# generated by `themer setup` — run by plasma-themer-picker.service
trig="{TRIGGER}"
mkdir -p "$trig" && rm -f "$trig"/show.*
echo $$ > "{CACHE / 'resident.pid'}"
export QML_XHR_ALLOW_FILE_READ=1 QT_QUICK_CONTROLS_STYLE=Basic QT_FORCE_STDERR_LOGGING=1
{soft}"{qml}" "{REPO / 'picker/Picker.qml'}" -- --resident "{DATA}" 2>&1 >/dev/null | while IFS= read -r line; do
  case $line in
    *APPLY:*) sel=${{line#*APPLY:}}; "{themer_bin}" pick-apply "${{sel%%:*}}" "${{sel#*:}}" & ;;
    *HIDDEN*) rm -f "$trig"/show.* ;;
  esac
done
""")
    RESIDENT.chmod(0o755)
    SERVICE.parent.mkdir(parents=True, exist_ok=True)
    SERVICE.write_text(f"""[Unit]
Description=plasma-themer picker (kept loaded so the hotkey opens it instantly)
PartOf=graphical-session.target
After=graphical-session.target

[Service]
ExecStart={RESIDENT}
Restart=on-failure
RestartSec=2

[Install]
WantedBy=graphical-session.target
""")
    return RESIDENT


def run_picker(apply) -> int:
    CACHE.mkdir(parents=True, exist_ok=True)
    lock = open(CACHE / "picker.lock", "w")
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        return 0  # already open
    data_file = write_data()
    # QT_FORCE_STDERR_LOGGING: with a piped stderr Qt logs to journald instead, and we'd never see APPLY:
    env = {**os.environ, "QML_XHR_ALLOW_FILE_READ": "1", "QT_QUICK_CONTROLS_STYLE": "Basic",
           "QT_FORCE_STDERR_LOGGING": "1"}
    if not any(Path("/dev/dri").glob("renderD*")):
        env["QT_QUICK_BACKEND"] = "software"  # no GPU: the picker uses no shaders, so this just works
    qml = qml_runtime()
    if not qml:
        print("themer: no Qt 6 QML runtime found (Arch: qt6-declarative, Fedora: qt6-qtdeclarative-devel, "
              "Debian/Ubuntu: qml-qt6 qml6-module-qtquick qml6-module-qtquick-window)")
        return 1
    proc = subprocess.Popen([qml, str(REPO / "picker/Picker.qml"), "--", str(data_file)],
                            stderr=subprocess.PIPE, stdout=subprocess.DEVNULL, text=True, env=env)
    worker = None
    for line in proc.stderr:
        if "APPLY:" in line:
            slug, _, bg = line.split("APPLY:", 1)[1].strip().partition(":")
            if bg:
                state_set(f"bg/{slug}", bg)
            worker = threading.Thread(target=apply, args=(slug,), kwargs={"quiet": True})
            worker.start()
    proc.wait()
    if worker:
        worker.join()
    return 0
